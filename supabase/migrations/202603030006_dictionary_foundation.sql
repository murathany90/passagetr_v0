create or replace function public.dictionary_bootstrap_manifest()
returns table (
  dataset_version text,
  batch_id uuid,
  row_count bigint,
  generated_at timestamptz
)
language sql
stable
as $$
with latest as (
  select b.id, b.dataset_version
  from public.dictionary_import_batches b
  where b.status = 'completed'
  order by b.completed_at desc nulls last, b.started_at desc
  limit 1
)
select
  l.dataset_version,
  l.id as batch_id,
  (select count(*)::bigint from public.dictionary_entries e where e.is_active = true) as row_count,
  now() as generated_at
from latest l
union all
select
  ''::text as dataset_version,
  null::uuid as batch_id,
  0::bigint as row_count,
  now() as generated_at
where not exists (select 1 from latest);
$$;

create or replace function public.dictionary_entries_bootstrap_page(
  p_after_seq_id bigint default 0,
  p_limit integer default 2000
)
returns table (
  seq_id bigint,
  id uuid,
  en_word text,
  en_word_normalized text,
  search_key text,
  pos text,
  tr_meaning text,
  source text,
  updated_at timestamptz
)
language sql
stable
as $$
select
  e.seq_id,
  e.id,
  e.en_word,
  e.en_word_normalized,
  e.search_key,
  e.pos,
  e.tr_meaning,
  e.source,
  e.updated_at
from public.dictionary_entries e
where e.is_active = true
  and e.seq_id > greatest(coalesce(p_after_seq_id, 0), 0)
order by e.seq_id asc
limit least(greatest(coalesce(p_limit, 2000), 1), 5000);
$$;

